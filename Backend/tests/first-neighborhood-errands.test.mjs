import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {FirstNeighborhoodErrandsReference as Ref,neighborhoodErrandsContract as contract}
 from "../src/services/first-neighborhood-errands-reference.mjs";
const root=new URL("../../GameClient/StarterAssets/Assets/_AfriLife/",import.meta.url);
const cs=p=>readFileSync(new URL(p,root),"utf8");
test("four optional activities are distinct and economic state is bounded by original wallet",()=>{
 assert.deepEqual(contract.activities.map(a=>a.id),["clinic-checkin","market-supplies","park-cleanup","neighbor-help"]);
 const sim=new Ref();
 assert.equal(sim.perform({id:"clinic-checkin",siteId:"clinic",day:0,nearby:true}).ok,true);
 assert.equal(sim.funds,4880);
 assert.equal(sim.needs.health,55);
 const duplicate=sim.perform({id:"clinic-checkin",siteId:"clinic",day:0,nearby:true});
 assert.equal(duplicate.replay,true);
 assert.equal(sim.funds,4880);
 assert.equal(sim.perform({id:"market-supplies",siteId:"market",day:0,nearby:true}).ok,true);
 assert.equal(sim.supplies,1);
 assert.equal(sim.funds,4700);
 assert.equal(sim.perform({id:"park-cleanup",siteId:"park",day:0,nearby:true}).ok,true);
 assert.equal(sim.funds,4775);
 assert.equal(sim.perform({id:"neighbor-help",siteId:"neighbor",day:0,nearby:true}).error,"resident_unavailable");
 assert.equal(sim.perform({id:"neighbor-help",siteId:"neighbor",day:0,nearby:true,residentReady:true}).ok,true);
 assert.equal(sim.needs.social,55);
 assert.equal(sim.receipts().length,4);
 const replay=Ref.restore(sim.export());
 assert.ok(replay);
 assert.equal(replay.funds,sim.funds);
 assert.equal(replay.perform({id:"park-cleanup",siteId:"park",day:0,nearby:true}).replay,true);
 assert.equal(replay.perform({id:"park-cleanup",siteId:"park",day:1,nearby:true}).replay,false);
});
test("distance, insufficient funds, duplicate replays, malformed restored ledgers",()=>{
 const sim=new Ref({fundsMinorUnits:75});
 assert.equal(sim.perform({id:"clinic-checkin",siteId:"clinic",day:0,nearby:true}).error,"insufficient_funds");
 assert.equal(sim.perform({id:"park-cleanup",siteId:"park",day:0,nearby:false}).error,"out_of_range");
 assert.equal(sim.funds,75);
 assert.equal(Ref.restore('{"funds":-1}'),null);
 const a=sim.perform({id:"park-cleanup",siteId:"park",day:0,nearby:true});
 assert.equal(a.ok,true);
 assert.equal(sim.funds,150);
 const saved=JSON.parse(sim.export());
 saved.receipts.push(saved.receipts[0]);
 assert.equal(Ref.restore(JSON.stringify(saved)),null);
});
